LANGS = ("ko", "en")
LANG_COOKIE = "hub_lang"
THEMES = ("light", "dark", "auto")
THEME_COOKIE = "hub_theme"


def translator(lang: str):
    """The text function of a language: t(key, **values). A key it does not have comes back as the key itself, so a
    missing text shows; t.has(key) says whether the key is there."""
    table = STRINGS.get(lang) or STRINGS["ko"]

    def t(key: str, **values) -> str:
        text = table.get(key, key)
        return text.format(**values) if values else text
    t.has = lambda key: key in table
    return t


def lang_of(request, default: str) -> str:
    """The page's language: ?lang= if it names one, else the cookie, else the default (HUB_UI_LANG); else ko."""
    for candidate in (request.query_params.get("lang"), request.cookies.get(LANG_COOKIE)):
        if candidate in LANGS:
            return candidate
    return default if default in LANGS else "ko"


def theme_of(request, default: str = "auto") -> str:
    """The page's theme: ?theme= if it names one, else the cookie, else the default (auto follows the OS)."""
    for candidate in (request.query_params.get("theme"), request.cookies.get(THEME_COOKIE)):
        if candidate in THEMES:
            return candidate
    return default if default in THEMES else "auto"
